// Usage: node scripts/check.mjs [--write] [--spec-dir DIR]
// Counts come from spec/manifest.json, never from literals. --write regenerates
// docs/OPERATIONS.md and docs/spec-changes/; without it, any drift fails. --spec-dir checks
// only another spec directory (manifest, hashes, keyword guard, counts); tests use it.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { SPEC_DIR } from '../src/catalog.mjs';
import { verifySpecSet, expectedReports, counts, dirUrl } from './spec-lib.mjs';

const args = process.argv.slice(2);
const write = args.includes('--write');
const at = args.indexOf('--spec-dir');
const customDir = at >= 0 ? args[at + 1] : null;
if (
  (at >= 0 && !customDir) ||
  args.some((a, i) => !['--write', '--spec-dir'].includes(a) && i !== at + 1)
) {
  console.error('Usage: node scripts/check.mjs [--write] [--spec-dir DIR]');
  process.exit(2);
}
const failures = [];
if (!customDir)
  for (const directory of ['src', 'scripts', 'test'])
    for (const file of readdirSync(new URL(`../${directory}/`, import.meta.url)))
      if (file.endsWith('.mjs'))
        execFileSync(
          process.execPath,
          ['--check', fileURLToPath(new URL(`../${directory}/${file}`, import.meta.url))],
          { stdio: 'pipe' },
        );

const { errors, catalogs } = verifySpecSet(customDir ? dirUrl(resolve(customDir)) : SPEC_DIR);
failures.push(...errors);
const fail = () => {
  console.error(failures.map((f) => `check: ${f}`).join('\n'));
  process.exit(1);
};
if (failures.length) fail();

const newest = catalogs.at(-1);
const versions = catalogs.map((c) => c.entry.version);
if (!customDir) {
  // Oldest retained bundled spec that contains each operation of the newest spec.
  const first = (id) => catalogs.find((c) => c.byId.has(id)).entry.version;
  const { operations, reads, mutations } = counts(newest);
  const rows = newest.operations
    .map(
      (o) =>
        `| \`${o.id}\` | ${o.method} | \`${o.path}\` | ${o.readOnly ? 'Read' : 'Preview → permitted apply'} | ${first(o.id)} |`,
    )
    .join('\n');
  const older = [
    ...new Set(
      catalogs.flatMap((c) => c.operations.filter((o) => !newest.byId.has(o.id)).map((o) => o.id)),
    ),
  ];
  const content = `# API operation coverage

Generated by \`node scripts/check.mjs --write\` from Ubiquiti's Network ${newest.entry.version} OpenAPI specification, the newest of the bundled specifications in \`spec/manifest.json\` (${versions.join(', ')}). All ${operations} of its operation IDs are registered: ${reads} reads and ${mutations} mutations. At startup the server activates the bundled specification that best matches the router; \`unifi_status\` reports which one, and a router on an older version gets that version's operations and request shapes. "First bundled in" is the oldest bundled specification that contains the operation. Per-version differences are in [spec-changes](spec-changes/).

Coverage means implementation/registration, not that every endpoint was executed against a router. Hardware and firmware can limit individual operations.

| Official operation ID | Method | API path | MCP behavior | First bundled in |
| --- | --- | --- | --- | --- |
${rows}
${older.length ? `\nOperations only in older bundled specifications: ${older.map((id) => `\`${id}\``).join(', ')}.\n` : ''}`;
  const outputs = [
    { url: new URL('../docs/OPERATIONS.md', import.meta.url), content },
    ...expectedReports(catalogs).map((r) => ({
      url: new URL(`../docs/spec-changes/${r.file}`, import.meta.url),
      content: r.content,
    })),
  ];
  for (const { url, content: expected } of outputs) {
    if (write) {
      mkdirSync(new URL('./', url), { recursive: true });
      writeFileSync(url, expected);
      continue;
    }
    let actual = null;
    try {
      actual = readFileSync(url, 'utf8');
    } catch {}
    if (actual !== expected)
      failures.push(
        `${fileURLToPath(url)
          .slice(fileURLToPath(new URL('../', import.meta.url)).length)
          .replaceAll(
            '\\',
            '/',
          )}: generated documentation drift; run node scripts/check.mjs --write`,
      );
  }
  if (failures.length) fail();
}
console.log(
  JSON.stringify({
    schemaVersion: newest.entry.version,
    bundled: catalogs.map((c) => ({ version: c.entry.version, ...counts(c) })),
    keywordGuard: 'pass',
    invokedOperations: 0,
  }),
);
